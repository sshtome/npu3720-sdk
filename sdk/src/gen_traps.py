#!/usr/bin/env python3
"""Generate traps_table.S: 256 x 16B trap table at 0x84803000."""
import sys

out_path = sys.argv[1] if len(sys.argv) > 1 else "traps_table.S"

lines = ["/* Auto-generated by gen_traps.py: 256 entries x 16B, base 0x84803000 */"]
for tt in range(256):
    entry = [f"trap_entry_{tt}:"]
    if tt == 0:
        entry += [
            "    sethi   %hi(_start), %l0",
            "    jmp     %l0 + %lo(_start)",
            "    nop",
            "    nop",
        ]
    elif tt == 5:
        entry += [
            "    sethi   %hi(window_overflow), %l0",
            "    jmp     %l0 + %lo(window_overflow)",
            "    nop",
            "    nop",
        ]
    elif tt == 6:
        entry += [
            "    sethi   %hi(window_underflow), %l0",
            "    jmp     %l0 + %lo(window_underflow)",
            "    nop",
            "    nop",
        ]
    elif tt == 9:
        entry += [
            "    sethi   %hi(fault_skip), %l0",
            "    jmp     %l0 + %lo(fault_skip)",
            "    nop",
            "    nop",
        ]
    else:
        entry += [
            f"    mov     {tt}, %g2",
            "    sethi   %hi(crash_handler), %l0",
            "    jmp     %l0 + %lo(crash_handler)",
            "    nop",
        ]
    lines.append("\n".join(entry))
    lines.append("    .align 16")

with open(out_path, "w") as f:
    f.write("\n".join(lines) + "\n")
